export async function getT() {
  const lang = await getLang();
  const t = (k: DictKey, vars?: Record<string, string | number>) =>
    vars ? dict[lang][k].replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? "")) : dict[lang][k];
  return { lang, t };
}
export type T = Awaited<ReturnType<typeof getT>>["t"];

