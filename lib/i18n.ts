import { cookies } from "next/headers";

export type Lang = "id" | "en";

export async function getLang(): Promise<Lang> {
  return (await cookies()).get("lang")?.value === "en" ? "en" : "id";
}

// Pick the localized column: pick(pkg, "title", "en") -> pkg.title_en, falling back to Indonesian.
export function pick<T extends Record<string, unknown>>(row: T, field: string, lang: Lang): string {
  const v = row[`${field}_${lang}`];
  return (typeof v === "string" && v) ? v : String(row[`${field}_id`] ?? "");
}
export function pickList<T extends Record<string, unknown>>(row: T, field: string, lang: Lang): string[] {
  const v = row[`${field}_${lang}`] as string[] | undefined;
  return v?.length ? v : ((row[`${field}_id`] as string[]) ?? []);
}

